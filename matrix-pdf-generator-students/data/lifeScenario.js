function lifeScenarioBlocksLength(blocks) {
  return (blocks || []).reduce(function(sum, block) {
    return sum + String(block.text || "").length;
  }, 0);
}

function lifeScenarioSectionLength(section) {
  if (!section) return 0;
  return String(section.title || "").length + lifeScenarioBlocksLength(section.blocks || []);
}

function makeLifeScenarioPage(kind, scenario, sections, options = {}) {
  const length = sections.reduce(function(sum, section) {
    if (section.kind === "intro") {
      return sum + lifeScenarioBlocksLength(section.blocks);
    }

    return sum + lifeScenarioSectionLength(section);
  }, 0);

  let density = "balanced";

  if (length < 1200) {
    density = "center";
  } else if (length > 3600) {
    density = "dense";
  }

  return {
    kind,
    density,
    scenario,
    sections,
    showTitle: Boolean(options.showTitle)
  };
}

function splitLongLifeScenarioSection(section, maxChars) {
  const parts = [];
  let currentBlocks = [];
  let currentLength = 0;

  (section.blocks || []).forEach(function(block) {
    const blockLength = String(block.text || "").length;

    if (
      currentBlocks.length > 0 &&
      (currentLength + blockLength > maxChars || block.strongPageBreak)
    ) {
      parts.push({
        ...section,
        blocks: currentBlocks
      });

      currentBlocks = [];
      currentLength = 0;
    }

    currentBlocks.push(block);
    currentLength += blockLength;
  });

  if (currentBlocks.length > 0) {
    parts.push({
      ...section,
      blocks: currentBlocks
    });
  }

  return parts.length > 0 ? parts : [section];
}

function splitLifeScenarioSectionHalf(section) {
  const blocks = section.blocks || [];

  if (blocks.length === 1) {
    const originalBlock = blocks[0];

    const lines = String(originalBlock.text || "")
      .split("\n")
      .map(function(line) {
        return line.trim();
      })
      .filter(Boolean);

    if (lines.length >= 8) {
      const middle = Math.ceil(lines.length / 2);

      return [
        {
          ...section,
          blocks: [
            {
              ...originalBlock,
              text: lines.slice(0, middle).join("\n")
            }
          ]
        },
        {
          ...section,
          blocks: [
            {
              ...originalBlock,
              text: lines.slice(middle).join("\n")
            }
          ]
        }
      ];
    }
  }

  const totalLength = blocks.reduce(function(sum, block) {
    return sum + String(block.text || "").length;
  }, 0);

  const halfLength = Math.ceil(totalLength / 2);
  const firstBlocks = [];
  const secondBlocks = [];
  let currentLength = 0;

  blocks.forEach(function(block) {
    const blockLength = String(block.text || "").length;

    if (currentLength < halfLength || firstBlocks.length === 0) {
      firstBlocks.push(block);
      currentLength += blockLength;
    } else {
      secondBlocks.push(block);
    }
  });

  if (secondBlocks.length === 0) {
    return [section];
  }

  return [
    {
      ...section,
      blocks: firstBlocks
    },
    {
      ...section,
      blocks: secondBlocks
    }
  ];
}

function getLifeScenarioPageLength(page) {
  if (!page || !page.sections) return 0;

  return page.sections.reduce(function(sum, section) {
    if (section.kind === "intro") {
      return sum + lifeScenarioBlocksLength(section.blocks);
    }

    return sum + lifeScenarioSectionLength(section);
  }, 0);
}

function buildLifeScenarioPages(scenario) {
  const parsed = splitLifeScenarioIntoSections(scenario.text || "");

  scenario.strategyTitle = parsed.strategyTitle || scenario.title || "Životní scénář";

  const introBlocks = parsed.intro || [];
  const sections = parsed.sections || [];

  const signalSections = sections.filter(function(section) {
    return section.type === "signals";
  });

  const newStrategySections = sections.filter(function(section) {
    return section.type === "newStrategy";
  });

  const stepSections = sections.filter(function(section) {
    return section.type === "steps";
  });

  const otherSections = sections.filter(function(section) {
    return (
      section.type !== "signals" &&
      section.type !== "newStrategy" &&
      section.type !== "steps"
    );
  });

  const firstPageSections = [];
  const secondPageSections = [];

  if (introBlocks.length > 0) {
    firstPageSections.push({
      kind: "intro",
      title: "",
      blocks: introBlocks
    });
  }

  otherSections.forEach(function(section) {
    firstPageSections.push(section);
  });

  signalSections.forEach(function(section) {
    firstPageSections.push(section);
  });

  newStrategySections.forEach(function(section) {
    secondPageSections.push(section);
  });

  stepSections.forEach(function(section) {
    secondPageSections.push(section);
  });

  const pages = [];

  if (firstPageSections.length > 0) {
    pages.push(
      makeLifeScenarioPage("title", scenario, firstPageSections, {
        showTitle: true
      })
    );
  }

  if (secondPageSections.length > 0) {
    pages.push(
      makeLifeScenarioPage("continue", scenario, secondPageSections, {
        showTitle: false
      })
    );
  }

  return pages;
}

function mergeTinyLifeScenarioPages(pages) {
  const result = [];

  pages.forEach(function(page) {
    const pageLen = getLifeScenarioPageLength(page);
    const previous = result[result.length - 1];
    const previousLen = getLifeScenarioPageLength(previous);

    if (
      previous &&
      !page.showTitle &&
      !previous.showTitle &&
      pageLen < 800 &&
      previousLen < 3300
    ) {
      previous.sections.push(...page.sections);

      const mergedLen = previousLen + pageLen;

      if (mergedLen < 1200) {
        previous.density = "center";
      } else if (mergedLen > 3600) {
        previous.density = "dense";
      } else {
        previous.density = "balanced";
      }

      return;
    }

    result.push(page);
  });

  return result;
}

