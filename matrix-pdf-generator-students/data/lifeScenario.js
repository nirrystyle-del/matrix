const LIFE_SCENARIO_SECTION_GROUPS = {
  signals: [
    "Signály",
    "Signály:"
  ],

  newStrategy: [
    "Nová strategie",
    "Nová strategie:"
  ],

  steps: [
    "Kroky",
    "Kroky:"
  ]
};

function normalizeLifeScenarioHeading(text) {
  return String(text || "")
    .replace(/[\u200B-\u200D\uFEFF]/g, "")
    .replace(/\u00A0/g, " ")
    .replace(/[：:]\s*$/, "")
    .replace(/\s+/g, " ")
    .trim();
}

function isLifeScenarioServiceLine(text) {
  const clean = String(text || "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();

  return (
    clean.startsWith("životní scénář") ||
    clean.startsWith("střed matice osudu")
  );
}

function isLifeScenarioStrategyHeading(text) {
  const clean = normalizeLifeScenarioHeading(text).toLowerCase();

  return (
    clean.startsWith("strategie ") ||
    clean.startsWith("strаtеgie ") ||
    clean.startsWith("stratégie ")
  );
}

function findInlineLifeScenarioHeading(line) {
  const rawLine = String(line || "")
    .replace(/[\u200B-\u200D\uFEFF]/g, "")
    .replace(/\u00A0/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  const normalizedLine = normalizeLifeScenarioHeading(rawLine);

  for (const [type, headings] of Object.entries(LIFE_SCENARIO_SECTION_GROUPS)) {
    for (const heading of headings) {
      const cleanHeading = normalizeLifeScenarioHeading(heading);

      if (normalizedLine === cleanHeading) {
        return {
          type,
          title: cleanHeading,
          rest: ""
        };
      }

      if (rawLine.startsWith(cleanHeading + ":")) {
        return {
          type,
          title: cleanHeading,
          rest: rawLine.slice((cleanHeading + ":").length).trim()
        };
      }

      if (rawLine.startsWith(cleanHeading + " :")) {
        return {
          type,
          title: cleanHeading,
          rest: rawLine.slice((cleanHeading + " :").length).trim()
        };
      }
    }
  }

  return null;
}

function splitLifeScenarioRawIntoBlocks(raw) {
  const lines = String(raw || "")
    .replace(/\r\n/g, "\n")
    .replace(/\r/g, "\n")
    .split("\n");

  const blocks = [];
  let currentLines = [];
  let blankCount = 0;
  let pendingBlankCount = 0;

  function pushCurrent() {
    const text = currentLines.join("\n").trim();

    if (!text) return;
    if (isLifeScenarioServiceLine(text)) {
      currentLines = [];
      pendingBlankCount = 0;
      return;
    }

    blocks.push({
      text,
      blankCountBefore: pendingBlankCount,
      forcePageBreak: pendingBlankCount >= 5,
      strongPageBreak: pendingBlankCount >= 8
    });

    currentLines = [];
    pendingBlankCount = 0;
  }

  lines.forEach(function(line) {
    if (line.trim() === "") {
      blankCount++;

      if (currentLines.length > 0) {
        pushCurrent();
      }

      pendingBlankCount = blankCount;
      return;
    }

    blankCount = 0;
    currentLines.push(line);
  });

  pushCurrent();

  return blocks;
}

function splitLifeScenarioBlockByHeadings(block) {
  const text = String(block.text || "").trim();
  if (!text) return [];

  const lines = text
    .split("\n")
    .map(function(line) {
      return line.trim();
    })
    .filter(Boolean)
    .filter(function(line) {
      return !isLifeScenarioServiceLine(line);
    });

  if (lines.length === 0) return [];

  const result = [];
  let currentText = "";
  let currentBlock = {
    ...block,
    text: "",
    isHeading: false,
    headingType: null,
    isStrategyHeading: false
  };

  function pushCurrentText() {
    const cleanText = String(currentText || "").trim();
    if (!cleanText) return;

    result.push({
      ...currentBlock,
      text: cleanText,
      isHeading: false,
      headingType: null,
      isStrategyHeading: false
    });

    currentText = "";
  }

  lines.forEach(function(line, index) {
    if (isLifeScenarioStrategyHeading(line)) {
      pushCurrentText();

      result.push({
        text: normalizeLifeScenarioHeading(line),
        blankCountBefore: index === 0 ? block.blankCountBefore : 2,
        forcePageBreak: index === 0 ? block.forcePageBreak : false,
        strongPageBreak: index === 0 ? block.strongPageBreak : false,
        isHeading: false,
        headingType: null,
        isStrategyHeading: true
      });

      currentBlock = {
        ...block,
        blankCountBefore: 0,
        forcePageBreak: false,
        strongPageBreak: false,
        isHeading: false,
        headingType: null,
        isStrategyHeading: false
      };

      return;
    }

    const foundHeading = findInlineLifeScenarioHeading(line);

    if (foundHeading) {
      pushCurrentText();

      result.push({
        text: foundHeading.title,
        blankCountBefore: index === 0 ? block.blankCountBefore : 2,
        forcePageBreak: index === 0 ? block.forcePageBreak : false,
        strongPageBreak: index === 0 ? block.strongPageBreak : false,
        isHeading: true,
        headingType: foundHeading.type,
        isStrategyHeading: false
      });

      currentBlock = {
        ...block,
        blankCountBefore: 0,
        forcePageBreak: false,
        strongPageBreak: false,
        isHeading: false,
        headingType: null,
        isStrategyHeading: false
      };

      if (foundHeading.rest) {
        currentText = foundHeading.rest;
      }

      return;
    }

    currentText += (currentText ? "\n" : "") + line;
  });

  pushCurrentText();

  return result.length > 0 ? result : [block];
}

function splitLifeScenarioIntoSections(raw) {
  const intro = [];
  const sections = [];
  let strategyTitle = "";
  let current = null;

  const expandedBlocks = [];

  splitLifeScenarioRawIntoBlocks(raw).forEach(function(block) {
    expandedBlocks.push(...splitLifeScenarioBlockByHeadings(block));
  });

  expandedBlocks.forEach(function(block) {
    if (block.isStrategyHeading) {
      strategyTitle = normalizeLifeScenarioHeading(block.text);
      return;
    }

    if (block.isHeading) {
      if (current) sections.push(current);

      current = {
        type: block.headingType,
        title: normalizeLifeScenarioHeading(block.text),
        blocks: [],
        forcePageBreak: block.forcePageBreak,
        strongPageBreak: block.strongPageBreak
      };

      return;
    }

    if (current) {
      current.blocks.push(block);
    } else {
      intro.push(block);
    }
  });

  if (current) sections.push(current);

  return {
    strategyTitle,
    intro,
    sections
  };
}

