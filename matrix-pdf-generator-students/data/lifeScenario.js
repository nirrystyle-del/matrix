function isLifeScenarioBulletLine(line) {
  const clean = String(line || "").trim();

  return (
    clean.startsWith("•") ||
    clean.startsWith("·") ||
    clean.startsWith("- ") ||
    /^\d+[\.\)]/.test(clean)
  );
}

function renderLifeScenarioInlineText(text) {
  return escapeHtml(text);
}

function renderLifeScenarioBlock(block) {
  const text = String(block.text || "").trim();
  if (!text) return "";

  const lines = text
    .split("\n")
    .map(function(line) {
      return line.trim();
    })
    .filter(Boolean);

  if (lines.length > 1 && lines.every(isLifeScenarioBulletLine)) {
    const items = lines.map(function(line) {
      const cleaned = line.replace(/^(•|·|-|\d+[\.\)])\s*/, "");
      return "<li>" + renderLifeScenarioInlineText(cleaned) + "</li>";
    }).join("");

    return '<ul class="life-scenario-print-list">' + items + "</ul>";
  }

  if (lines.length > 1 && lines.some(isLifeScenarioBulletLine)) {
    return lines.map(function(line) {
      if (isLifeScenarioBulletLine(line)) {
        const cleaned = line.replace(/^(•|·|-|\d+[\.\)])\s*/, "");
        return '<ul class="life-scenario-print-list single"><li>' + renderLifeScenarioInlineText(cleaned) + "</li></ul>";
      }

      return "<p>" + renderLifeScenarioInlineText(line) + "</p>";
    }).join("");
  }

  const compact = text.replace(/\n+/g, " ").replace(/\s+/g, " ").trim();

  return "<p>" + renderLifeScenarioInlineText(compact) + "</p>";
}

function renderLifeScenarioBlocks(blocks) {
  return (blocks || []).map(renderLifeScenarioBlock).join("");
}

function renderLifeScenarioSection(section) {
  if (!section) return "";

  if (section.kind === "intro") {
    return (
      '<div class="life-scenario-print-section life-scenario-print-section-intro">' +
        '<div class="life-scenario-print-text">' +
          renderLifeScenarioBlocks(section.blocks) +
        "</div>" +
      "</div>"
    );
  }

  const title = section.title
    ? '<h3 class="life-scenario-print-subtitle life-scenario-print-subtitle-' + escapeHtml(section.type) + '">' + escapeHtml(section.title) + "</h3>"
    : "";

  return (
    '<div class="life-scenario-print-section life-scenario-print-section-' + escapeHtml(section.type) + '">' +
      title +
      '<div class="life-scenario-print-text">' +
        renderLifeScenarioBlocks(section.blocks) +
      "</div>" +
    "</div>"
  );
}

function renderLifeScenarioPage(page) {
  const scenario = page.scenario;

  const titleHTML = page.showTitle
    ? (
      '<div class="life-scenario-print-title-block">' +
        '<div class="life-scenario-print-overline">SCÉNÁŘ</div>' +
        '<h2>Životní scénář</h2>' +
        '<div class="life-scenario-print-strategy">' + escapeHtml(scenario.strategyTitle || scenario.title || "") + "</div>" +
      "</div>"
    )
    : "";

  const sectionsHTML = page.sections.map(renderLifeScenarioSection).join("");

  return (
    '<section class="life-scenario-print-page life-scenario-page-' + escapeHtml(page.kind) + " life-scenario-density-" + escapeHtml(page.density) + '">' +
      '<div class="life-scenario-print-inner">' +
        titleHTML +
        sectionsHTML +
      "</div>" +
    "</section>"
  );
}

