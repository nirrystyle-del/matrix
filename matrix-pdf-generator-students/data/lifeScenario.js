function escapeHtml(value) {
  return String(value == null ? "" : value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function getLifeScenarioKey(result) {
  return [result.D1, result.D2, result.D].map(String).join("-");
}

function findLifeScenario(result) {
  const karmaKey = getLifeScenarioKey(result);
  const centerKey = String(result.E);

  const matches = lifeScenarioDatabase.filter(function(item) {
    return String(item.karmaKey) === karmaKey;
  });

  if (matches.length === 0) {
    return {
      key: karmaKey,
      center: centerKey,
      item: null
    };
  }

  const centerMatch = matches.find(function(item) {
    return String(item.center) === centerKey;
  });

  return {
    key: karmaKey,
    center: centerKey,
    item: centerMatch || matches[0]
  };
}

